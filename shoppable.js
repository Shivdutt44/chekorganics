/* ==========================================================================
   CHEKORGANICS — shoppable videos (homepage "Watch & shop")
   Data: videos.js (generated by .build/fetch-videos.mjs). Load after app.js.

   Rail: reels-style cards; cards on screen autoplay muted (never with
   reduced motion or Data Saver), sources attach only when near the viewport.
   Viewer: full-screen player with sound, swipe/arrow navigation and the
   tagged product (live price + stock from chekorganics.com, Add to bag).
   ========================================================================== */
(function () {
  "use strict";

  const DATA = window.SHOPPABLE_VIDEOS;
  const LIVE = "https://www.chekorganics.com";
  const $ = (sel, root) => (root || document).querySelector(sel);
  const esc = s => String(s == null ? "" : s).replace(/[&<>"']/g, c => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" }[c]));
  const money = n => "₹" + Number(n).toLocaleString("en-IN", { maximumFractionDigits: 0 });
  const reduceMotion = window.matchMedia("(prefers-reduced-motion: reduce)");
  const saveData = !!(navigator.connection && navigator.connection.saveData);
  const snapshot = new Map(((window.STORE && window.STORE.products) || []).map(p => [p.handle, p]));

  function shortName(raw) {
    const t = String(raw || "").replace(/\s+/g, " ").trim();
    const m = t.match(/^(.{3,62}?)\s+[-–—]\s+(.+)$/);
    let name = m ? m[2] : t;
    if (name.includes("|")) {
      const head = name.split("|")[0].trim();
      if (head.length > 12) name = head;
    }
    return name.replace(/^CHEKORGANICS?\s+(BODYHUES\s+)?[-–—]?\s*/i, "") || t;
  }

  const thumb = (url, w) => {
    if (!url) return "";
    if (/^assets\//.test(url)) return url;
    try {
      const u = new URL(url, location.href);
      if (u.hostname === "cdn.shopify.com" || u.pathname.startsWith("/cdn/shop/")) u.searchParams.set("width", String(w));
      return u.toString();
    } catch (e) {
      return url;
    }
  };
  const fmtTime = s => (s == null || !isFinite(s) ? "" : Math.floor(s / 60) + ":" + String(Math.floor(s % 60)).padStart(2, "0"));

  /* ----------------------------------------------- product data (live → snapshot) */
  const liveCache = new Map();
  function productInfo(handle) {
    const p = snapshot.get(handle);
    return {
      handle,
      title: shortName(p ? p.title : handle.replace(/-/g, " ")),
      image: p && p.images ? p.images[0] : null,
      price: p ? p.price : null,
      compareAt: p ? p.compareAt : null,
      available: p ? p.available !== false : null,
    };
  }
  function liveProduct(handle) {
    if (!liveCache.has(handle)) {
      liveCache.set(handle, fetch(LIVE + "/products/" + encodeURIComponent(handle) + ".js", { credentials: "omit" })
        .then(r => (r.ok ? r.json() : null))
        .then(j => {
          if (!j) return null;
          const price = Number(j.price) / 100;
          const cmp = j.compare_at_price ? Number(j.compare_at_price) / 100 : null;
          return { price, compareAt: cmp && cmp > price ? cmp : null, available: !!j.available };
        })
        .catch(() => null));
    }
    return liveCache.get(handle);
  }

  function priceHtml(info) {
    if (info.price == null) return "";
    return '<span class="vprice">' + money(info.price) + (info.compareAt ? " <s>" + money(info.compareAt) + "</s>" : "") + "</span>";
  }

  /* ------------------------------------------------------------- the rail */
  function init() {
    const rail = document.getElementById("video-rail");
    if (!DATA || !Array.isArray(DATA.videos) || !rail) return;
    const videos = DATA.videos.filter(v => v.products && v.products.some(h => snapshot.has(h)));
    if (!videos.length) {
      const section = rail.closest("section");
      if (section) section.hidden = true;
      return;
    }

    rail.innerHTML = videos
      .map((v, i) => {
        const info = productInfo(v.products[0]);
        const landscape = v.width && v.height && v.width > v.height;
        return (
          '<article class="vcard' + (landscape ? " vcard--wide" : "") + '" data-index="' + i + '">' +
          '<button class="vcard__play" type="button" aria-label="Play video: ' + esc(info.title) + '">' +
          (landscape ? '<img class="vcard__bg" src="' + esc(thumb(v.poster, 360)) + '" alt="" loading="lazy" decoding="async">' : "") +
          '<video class="vcard__video" muted playsinline loop preload="none" poster="' + esc(thumb(v.poster, 540)) + '" data-src="' + esc(v.sd || v.hd) + '" aria-hidden="true"></video>' +
          '<span class="vcard__badge"><svg viewBox="0 0 24 24" fill="currentColor" aria-hidden="true"><path d="M8 5.5v13l11-6.5z"/></svg>' + (v.duration ? fmtTime(v.duration) : "Watch") + "</span>" +
          "</button>" +
          '<div class="vcard__shop">' +
          (info.image ? '<img src="' + esc(thumb(info.image, 120)) + '" alt="" loading="lazy" decoding="async" width="44" height="44">' : "") +
          '<a class="vcard__name" href="product?p=' + encodeURIComponent(info.handle) + '">' + esc(info.title) + "</a>" +
          '<span class="vcard__price" data-price-for="' + esc(info.handle) + '">' + priceHtml(info) + "</span>" +
          '<button class="vcard__add" type="button" data-add="' + esc(info.handle) + '" aria-label="Add ' + esc(info.title) + ' to bag"' + (info.available === false ? " disabled" : "") + ">" +
          '<svg viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2.2" stroke-linecap="round" aria-hidden="true"><path d="M12 5v14M5 12h14"/></svg></button>' +
          "</div></article>"
        );
      })
      .join("");

    // live prices for the rail (one small request per tagged product, once the section is near)
    const refreshPrices = () =>
      [...new Set(videos.map(v => v.products[0]))].forEach(h =>
        liveProduct(h).then(lp => {
          if (!lp) return;
          const info = { ...productInfo(h), ...lp };
          document.querySelectorAll('[data-price-for="' + CSS.escape(h) + '"]').forEach(el => (el.innerHTML = priceHtml(info)));
          document.querySelectorAll('.vcard__add[data-add="' + CSS.escape(h) + '"]').forEach(b => (b.disabled = !lp.available));
        })
      );

    const autoplay = !reduceMotion.matches && !saveData && "IntersectionObserver" in window;
    const cards = [...rail.querySelectorAll(".vcard")];

    const near = new IntersectionObserver(entries => {
      entries.forEach(e => {
        if (!e.isIntersecting) return;
        const vid = $(".vcard__video", e.target);
        if (!vid.src && autoplay) vid.src = vid.dataset.src;
        near.unobserve(e.target);
      });
    }, { rootMargin: "300px 300px" });
    const visible = new IntersectionObserver(entries => {
      entries.forEach(e => {
        const vid = $(".vcard__video", e.target);
        if (e.isIntersecting && e.intersectionRatio >= 0.6 && !viewerOpen()) {
          if (!vid.src) vid.src = vid.dataset.src;
          vid.play().then(() => e.target.classList.add("is-playing")).catch(() => {});
        } else {
          vid.pause();
          e.target.classList.remove("is-playing");
        }
      });
    }, { threshold: [0, 0.6] });

    const section = rail.closest("section") || rail;
    new IntersectionObserver((entries, obs) => {
      if (entries.some(e => e.isIntersecting)) {
        refreshPrices();
        obs.disconnect();
      }
    }, { rootMargin: "400px" }).observe(section);

    if (autoplay) cards.forEach(c => {
      near.observe(c);
      visible.observe(c);
    });

    rail.addEventListener("click", e => {
      if (e.target.closest("[data-add], a")) return; // app.js handles Add to bag; links navigate
      const card = e.target.closest(".vcard");
      if (card) openViewer(videos, Number(card.dataset.index), card);
    });

    document.addEventListener("visibilitychange", () => {
      if (document.hidden) cards.forEach(c => $(".vcard__video", c).pause());
    });
    pauseRail = () => cards.forEach(c => {
      $(".vcard__video", c).pause();
      c.classList.remove("is-playing");
    });
  }

  let pauseRail = () => {};

  /* ------------------------------------------------------------ the viewer */
  let viewer = null, state = null;
  const viewerOpen = () => !!(viewer && viewer.classList.contains("is-open"));

  function buildViewer() {
    viewer = document.createElement("div");
    viewer.className = "vviewer";
    viewer.setAttribute("role", "dialog");
    viewer.setAttribute("aria-modal", "true");
    viewer.setAttribute("aria-label", "Shoppable video");
    viewer.innerHTML =
      '<div class="vviewer__stage">' +
      '<img class="vviewer__bg" alt="" aria-hidden="true">' +
      '<video class="vviewer__video" playsinline loop preload="auto"></video>' +
      '<div class="vviewer__progress" aria-hidden="true"><span></span></div>' +
      '<div class="vviewer__count" aria-live="polite"></div>' +
      '<button class="vviewer__btn vviewer__close" type="button" aria-label="Close video"><svg viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2.2" stroke-linecap="round"><path d="M6 6l12 12M18 6 6 18"/></svg></button>' +
      '<button class="vviewer__btn vviewer__sound" type="button" aria-label="Mute"></button>' +
      '<button class="vviewer__btn vviewer__prev" type="button" aria-label="Previous video"><svg viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2.2" stroke-linecap="round" stroke-linejoin="round"><path d="m15 6-6 6 6 6"/></svg></button>' +
      '<button class="vviewer__btn vviewer__next" type="button" aria-label="Next video"><svg viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2.2" stroke-linecap="round" stroke-linejoin="round"><path d="m9 6 6 6-6 6"/></svg></button>' +
      '<span class="vviewer__paused" aria-hidden="true"><svg viewBox="0 0 24 24" fill="currentColor"><path d="M8 5.5v13l11-6.5z"/></svg></span>' +
      "</div>" +
      '<div class="vviewer__shop"></div>';
    document.body.appendChild(viewer);

    const video = $(".vviewer__video", viewer);
    $(".vviewer__close", viewer).addEventListener("click", closeViewer);
    $(".vviewer__prev", viewer).addEventListener("click", () => go(-1));
    $(".vviewer__next", viewer).addEventListener("click", () => go(1));
    $(".vviewer__sound", viewer).addEventListener("click", () => {
      video.muted = !video.muted;
      paintSound();
    });
    video.addEventListener("click", () => (video.paused ? video.play().catch(() => {}) : video.pause()));
    video.addEventListener("play", () => viewer.classList.remove("is-paused"));
    video.addEventListener("pause", () => viewer.classList.add("is-paused"));
    video.addEventListener("timeupdate", () => {
      const p = video.duration ? video.currentTime / video.duration : 0;
      $(".vviewer__progress span", viewer).style.transform = "scaleX(" + p + ")";
    });
    viewer.addEventListener("keydown", e => {
      if (e.key === "Escape") {
        if (!document.querySelector(".drawer.is-open")) closeViewer();
      } else if (e.key === "ArrowRight" || e.key === "ArrowDown") { e.preventDefault(); go(1); }
      else if (e.key === "ArrowLeft" || e.key === "ArrowUp") { e.preventDefault(); go(-1); }
      else if (e.key === " " && e.target === viewer) { e.preventDefault(); video.paused ? video.play() : video.pause(); }
      else if (e.key === "Tab") trapFocus(e);
    });

    // swipe: vertical (reels) or horizontal
    let sx = 0, sy = 0, st = 0;
    const stage = $(".vviewer__stage", viewer);
    stage.addEventListener("touchstart", e => {
      const t = e.touches[0];
      sx = t.clientX;
      sy = t.clientY;
      st = Date.now();
    }, { passive: true });
    stage.addEventListener("touchend", e => {
      const t = e.changedTouches[0];
      const dx = t.clientX - sx, dy = t.clientY - sy;
      if (Date.now() - st > 700) return;
      if (Math.abs(dy) > 60 && Math.abs(dy) > Math.abs(dx)) go(dy < 0 ? 1 : -1);
      else if (Math.abs(dx) > 60) go(dx < 0 ? 1 : -1);
    }, { passive: true });

    // Add to bag opens app.js's drawer on top; pause so the video doesn't play behind it
    viewer.addEventListener("click", e => {
      if (e.target.closest("[data-add]")) video.pause();
    });
  }

  function trapFocus(e) {
    const f = [...viewer.querySelectorAll("button:not([disabled]), a[href]")].filter(el => el.offsetParent !== null);
    if (!f.length) return;
    const first = f[0], last = f[f.length - 1];
    if (e.shiftKey && document.activeElement === first) { e.preventDefault(); last.focus(); }
    else if (!e.shiftKey && document.activeElement === last) { e.preventDefault(); first.focus(); }
  }

  function paintSound() {
    const video = $(".vviewer__video", viewer);
    const btn = $(".vviewer__sound", viewer);
    btn.setAttribute("aria-label", video.muted ? "Unmute" : "Mute");
    btn.innerHTML = video.muted
      ? '<svg viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round"><path d="M4 9.5h3.5L12 6v12l-4.5-3.5H4z"/><path d="m16 9.5 5 5M21 9.5l-5 5"/></svg>'
      : '<svg viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round"><path d="M4 9.5h3.5L12 6v12l-4.5-3.5H4z"/><path d="M16 9a4.5 4.5 0 0 1 0 6M18.5 6.5a8 8 0 0 1 0 11"/></svg>';
  }

  function openViewer(videos, index, returnFocusTo) {
    if (!viewer) buildViewer();
    pauseRail();
    state = { videos, index, returnFocusTo, muted: false };
    viewer.classList.add("is-open");
    document.documentElement.classList.add("vviewer-lock");
    show(index, true);
    $(".vviewer__close", viewer).focus({ preventScroll: true });
  }

  function closeViewer() {
    if (!viewerOpen()) return;
    const video = $(".vviewer__video", viewer);
    video.pause();
    video.removeAttribute("src");
    video.load();
    viewer.classList.remove("is-open");
    document.documentElement.classList.remove("vviewer-lock");
    if (state && state.returnFocusTo) state.returnFocusTo.querySelector(".vcard__play").focus({ preventScroll: true });
  }

  function go(dir) {
    if (!state) return;
    const n = state.videos.length;
    show((state.index + dir + n) % n, false);
  }

  function show(index, fromGesture) {
    state.index = index;
    const v = state.videos[index];
    const video = $(".vviewer__video", viewer);
    // 720p starts fast and is sharp enough for a 9:16 player; 1080p only on very tall screens
    const big = window.innerHeight > 900 && !saveData;
    $(".vviewer__bg", viewer).src = thumb(v.poster, 360);
    video.poster = thumb(v.poster, 900);
    video.src = (big ? v.fhd || v.hd : saveData ? v.sd || v.hd : v.hd || v.sd) || v.sd;
    video.classList.toggle("is-wide", !!(v.width && v.height && v.width > v.height));
    if (fromGesture) video.muted = false; // opened by a tap: sound is allowed
    paintSound();
    const p = video.play();
    if (p) p.catch(err => {
      // Only a policy refusal (sound not allowed) is retried muted. An AbortError just
      // means we paused or switched videos while it was loading — leave it paused.
      if (!err || err.name !== "NotAllowedError" || !viewerOpen()) return;
      video.muted = true;
      paintSound();
      video.play().catch(() => viewer.classList.add("is-paused"));
    });
    $(".vviewer__count", viewer).textContent = index + 1 + " / " + state.videos.length;
    renderShop(v);
    // warm the next poster
    const next = state.videos[(index + 1) % state.videos.length];
    if (next && next.poster) new Image().src = thumb(next.poster, 900);
  }

  function renderShop(v) {
    const box = $(".vviewer__shop", viewer);
    const items = v.products.filter(h => snapshot.has(h)).map(productInfo);
    box.innerHTML = items
      .map(info =>
        '<div class="vshop" data-handle="' + esc(info.handle) + '">' +
        (info.image ? '<img src="' + esc(thumb(info.image, 200)) + '" alt="" width="64" height="64">' : "") +
        '<div class="vshop__text"><span class="vshop__kicker">Featured in this video</span>' +
        '<a class="vshop__name" href="product?p=' + encodeURIComponent(info.handle) + '">' + esc(info.title) + "</a>" +
        '<span class="vshop__price" data-price-for="' + esc(info.handle) + '">' + priceHtml(info) + "</span>" +
        '<span class="vshop__stock" data-stock-for="' + esc(info.handle) + '"></span></div>' +
        '<div class="vshop__actions">' +
        '<button class="btn btn--primary vshop__add" type="button" data-add="' + esc(info.handle) + '"' + (info.available === false ? " disabled" : "") + ">Add to bag</button>" +
        '<a class="btn btn--ghost vshop__view" href="product?p=' + encodeURIComponent(info.handle) + '">View product</a></div></div>'
      )
      .join("");
    items.forEach(info =>
      liveProduct(info.handle).then(lp => {
        if (!lp || !viewerOpen()) return;
        const row = box.querySelector('.vshop[data-handle="' + CSS.escape(info.handle) + '"]');
        if (!row) return;
        $(".vshop__price", row).innerHTML = priceHtml({ ...info, ...lp });
        $(".vshop__stock", row).textContent = lp.available ? "In stock" : "Currently sold out";
        $(".vshop__stock", row).classList.toggle("is-out", !lp.available);
        $(".vshop__add", row).disabled = !lp.available;
      })
    );
  }

  document.addEventListener("DOMContentLoaded", init);
  // the app shell's drawer has its own Escape handling; close the viewer first
  document.addEventListener("keydown", e => {
    if (e.key === "Escape" && viewerOpen() && !document.querySelector(".drawer.is-open")) closeViewer();
  });
})();
