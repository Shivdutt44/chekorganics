// Pulls the store's real Judge.me reviews (text, rating, photos, shop replies) for every
// product in data.js and writes reviews-data.js (window.CHEK_REVIEWS), which app.js shows on
// product pages and in the home page's customer-photo section.
//
//   node .build/fetch-reviews.mjs        (run from the site root; re-run to refresh)
//
// Uses Judge.me's public widget endpoint, the same one the live Shopify store's review
// widget calls. Nothing is invented: only reviews customers actually left are written.
import fs from "fs";
import vm from "vm";

const SHOP = "epyx6c-qg.myshopify.com"; // chekorganics.com's Shopify domain
const OUT = "reviews-data.js";

const sandbox = { window: {} };
vm.runInNewContext(fs.readFileSync("data.js", "utf8"), sandbox);
const products = sandbox.window.STORE.products;

const text = html => String(html || "")
  .replace(/<br\s*\/?>/gi, "\n").replace(/<\/p>\s*<p>/gi, "\n\n").replace(/<[^>]+>/g, "")
  .replace(/&amp;/g, "&").replace(/&lt;/g, "<").replace(/&gt;/g, ">").replace(/&quot;/g, '"').replace(/&#39;|&#x27;/g, "'").replace(/&nbsp;/g, " ")
  .replace(/[ \t]+\n/g, "\n").trim();

async function reviewsFor(p) {
  const all = [];
  let summary = null;
  for (let page = 1; page <= 20; page++) {
    const url = `https://judge.me/reviews/reviews_for_widget?url=${SHOP}&shop_domain=${SHOP}&platform=shopify&page=${page}&per_page=50&product_id=${p.id}`;
    const res = await fetch(url, { headers: { "user-agent": "CHEKORGANICS-site-build/1.0" } });
    if (!res.ok) throw new Error(`${p.handle}: HTTP ${res.status}`);
    const j = await res.json();
    if (!summary) summary = { count: Number(j.number_of_reviews) || 0, rating: Number(j.average_rating) || 0, histogram: Object.fromEntries((j.histogram || []).map(h => [h.rating, h.frequency])) };
    const list = (j.primary_language_reviews || []).concat(j.other_language_reviews || [], j.reviews || []);
    list.forEach(r => all.push({
      id: "jdgm_" + r.uuid,
      author: r.is_anonymous_reviewer ? "Anonymous" : (r.reviewer_name || "Customer"),
      rating: Number(r.rating) || 0,
      title: text(r.title),
      body: text(r.body_html),
      createdAt: new Date(String(r.created_at).replace(" UTC", "Z").replace(" ", "T")).toISOString(),
      verified: !!r.verified_buyer,
      location: r.location || "",
      photos: (r.pictures_urls || []).map(x => ({ small: x.compact || x.small, large: x.huge || x.original })).filter(x => x.small && x.large),
      reply: text(r.reply_content),
      source: "judgeme"
    }));
    const pag = j.primary_language_pagination || {};
    if (!pag.total_pages || page >= pag.total_pages) break;
  }
  const seen = new Set();
  return { summary, reviews: all.filter(r => !seen.has(r.id) && seen.add(r.id)) };
}

const out = {};
let total = 0, photos = 0;
for (const p of products) {
  if (!p.id) continue;
  try {
    const { summary, reviews } = await reviewsFor(p);
    if (!summary || !summary.count) continue;
    out[p.handle] = { rating: summary.rating, count: summary.count, histogram: summary.histogram, reviews };
    total += reviews.length;
    photos += reviews.reduce((n, r) => n + r.photos.length, 0);
    console.log(`${String(summary.count).padStart(3)} reviews · ${summary.rating.toFixed(2)}★  ${p.handle}`);
  } catch (e) {
    console.warn("skipped", p.handle, e.message);
  }
}

fs.writeFileSync(OUT,
  "/* Real customer reviews from Judge.me (chekorganics.com), generated by .build/fetch-reviews.mjs on " +
  new Date().toISOString().slice(0, 10) + ". Do not edit by hand. */\n" +
  "window.CHEK_REVIEWS = " + JSON.stringify(out) + ";\n");
console.log(`\n${Object.keys(out).length} products, ${total} reviews, ${photos} photos → ${OUT}`);
