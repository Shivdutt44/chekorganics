/* ==========================================================================
   Builds ../videos.js — the shoppable video data for the homepage.

   Sources (both are the brand's own videos, hosted on Shopify's CDN):
     1. the shoppable video widget on the live homepage (its JSON config lists
        each video, its first-frame preview and the product it is tagged with)
     2. product media: videos attached to products (/products/{handle}.js)

   Usage:  cd .build && node fetch-videos.mjs
   No dependencies (Node 18+).
   ========================================================================== */
import fs from "node:fs";
import path from "node:path";

const STORE = "https://www.chekorganics.com";
const OUT = path.resolve("..", "videos.js");
const UA = { "user-agent": "CHEKORGANICS-preview-build/1.0" };

const get = async (url, as = "json") => {
  const r = await fetch(url, { headers: UA });
  if (!r.ok) throw new Error(`${r.status} ${url}`);
  return as === "json" ? r.json() : r.text();
};

// Shopify video id = the hash in /videos/c/(o/v|vp)/<hash>
const videoId = url => (/\/videos\/c\/(?:o\/v|vp\/[0-9a-f]+)\/([0-9a-f]{32})/.exec(url) || /\/videos\/c\/vp\/([0-9a-f]{32})\//.exec(url) || [])[1] || null;
const heightOf = url => Number((/-(\d{3,4})p-/.exec(url) || [])[1]) || null;

function pickSources(list) {
  const mp4 = list
    .map(s => (typeof s === "string" ? { url: s, height: heightOf(s), format: s.endsWith(".m3u8") ? "m3u8" : "mp4" } : { url: s.url, height: s.height || heightOf(s.url), format: s.format }))
    .filter(s => s.url && s.format === "mp4" && s.height)
    .sort((a, b) => a.height - b.height);
  const pick = h => (mp4.filter(s => s.height <= h).pop() || mp4[0] || {}).url || null;
  return { sd: pick(480), hd: pick(720), fhd: pick(1080) };
}

const videos = new Map();

/* 1 — homepage shoppable video widget */
const html = await get(STORE + "/", "text");
let widget = 0;
for (const m of html.matchAll(/<script type="application\/json" class="data">([\s\S]*?)<\/script>/g)) {
  let cfg;
  try {
    cfg = JSON.parse(m[1]);
  } catch {
    continue;
  }
  if (!Array.isArray(cfg.media)) continue;
  for (const v of cfg.media) {
    if (v.contentType !== "Video") continue;
    const id = videoId(v.originalSource || "") || videoId((v.sources || [])[0] || "");
    const products = (v.productProfile?.products || []).map(p => p.product?.handle).filter(Boolean);
    if (!id || videos.has(id) || !products.length) continue;
    videos.set(id, {
      id,
      origin: "homepage",
      poster: v.url || null,
      width: v.width || null,
      height: v.height || null,
      duration: null,
      ...pickSources(v.sources || []),
      products,
    });
    widget++;
  }
}

/* 2 — videos attached to products */
const { products } = await get(STORE + "/products.json?limit=250");
let productVideos = 0;
for (const p of products) {
  const js = await get(`${STORE}/products/${encodeURIComponent(p.handle)}.js`).catch(() => null);
  for (const media of js?.media || []) {
    if (media.media_type !== "video") continue;
    const id = videoId((media.sources || [])[0]?.url || "");
    if (!id) continue;
    if (videos.has(id)) {
      const v = videos.get(id);
      if (!v.products.includes(p.handle)) v.products.push(p.handle);
      v.duration = v.duration || (media.duration ? Math.round(media.duration / 1000) : null);
      continue;
    }
    videos.set(id, {
      id,
      origin: "product",
      poster: media.preview_image?.src || null,
      width: media.preview_image?.width || media.width || null,
      height: media.preview_image?.height || media.height || null,
      duration: media.duration ? Math.round(media.duration / 1000) : null,
      ...pickSources(media.sources || []),
      products: [p.handle],
    });
    productVideos++;
  }
}

const list = [...videos.values()].filter(v => v.sd || v.hd);
const out =
  "/* Generated by .build/fetch-videos.mjs — do not edit by hand.\n" +
  "   Shoppable videos from chekorganics.com (homepage video widget + product media). */\n" +
  "window.SHOPPABLE_VIDEOS = " +
  JSON.stringify({ generatedAt: new Date().toISOString(), store: STORE, videos: list }, null, 1) +
  ";\n";
fs.writeFileSync(OUT, out);
console.log(`homepage widget: ${widget} · product videos: ${productVideos} · total: ${list.length} → ${OUT}`);
